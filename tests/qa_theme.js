// dark mode switch: overrides the device and a host-set theme, survives reload
const { chromium } = require('playwright');
const { ok, openChooser, HTTP, OUT } = require('./qa_helpers');
const path = require('path');
(async () => { const SRV = await require('./qa_serve')();
  const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, colorScheme: 'light' });
  const pg = await ctx.newPage(); await pg.addInitScript(() => { try { localStorage.setItem('slideRead.welcomed', '1'); } catch (e) {} }); pg.on('pageerror', e => console.log('PAGEERR', e.message));
  await pg.goto(SRV.base + 'slide-and-read.html'); await pg.waitForTimeout(400);
  const bg = () => pg.evaluate(() => getComputedStyle(document.body).backgroundColor);
  const light = await bg();
  await pg.evaluate(() => { document.querySelectorAll('.cover').forEach(c => c.hidden = true); $('gearBtn').click(); });
  await pg.click('#themeSeg [data-v=dark]'); await pg.waitForTimeout(100);
  const dark = await bg(); ok('Dark turns the app dark on a light device', dark !== light, light + ' -> ' + dark);
  await pg.evaluate(() => document.documentElement.setAttribute('data-theme', 'light')); await pg.waitForTimeout(100);
  ok('stays dark when the host sets light', (await bg()) === dark);
  await pg.screenshot({ path: OUT + '/dark_settings.png' });
  await pg.reload(); await pg.waitForTimeout(400);
  ok('Dark survives a reload', (await bg()) === dark);
  await pg.evaluate(() => { document.querySelectorAll('.cover').forEach(c => c.hidden = true); $('gearBtn').click(); });
  await pg.click('#themeSeg [data-v=auto]'); await pg.waitForTimeout(100);
  ok('Auto goes back to following the device', (await bg()) === light);
  await pg.emulateMedia({ colorScheme: 'dark' }); await pg.waitForTimeout(100);
  ok('Auto follows a dark device', (await bg()) === dark);
  await pg.click('#themeSeg [data-v=light]'); await pg.waitForTimeout(100);
  ok('Light overrides a dark device', (await bg()) === light);
  await pg.click('#themeSeg [data-v=dark]'); await pg.evaluate(() => { $('sheet').hidden = true; current = { w: 'ship', ord: 1045 }; setup(); });
  await pg.waitForTimeout(300); await pg.screenshot({ path: OUT + '/dark_word.png' });
  await b.close(); SRV.close();
})();
